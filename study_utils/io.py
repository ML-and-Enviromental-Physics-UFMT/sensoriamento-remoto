"""I/O helpers for chapter exercises and scripts.

Raster arrays returned by ``read_raster`` use shape ``(bands, rows, cols)``
for multi-band images, or ``(rows, cols)`` for single-band. This matches
GDAL / Canty book convention (band-first).
"""

from __future__ import annotations

from pathlib import Path
from typing import Optional, Tuple, Union

import numpy as np

PathLike = Union[str, Path]


def repo_root() -> Path:
    """Return the repository root (parent of ``study_utils/``)."""
    return Path(__file__).resolve().parent.parent


def example_path() -> Path:
    """Path to the synthetic multiband sample generated by this project."""
    return repo_root() / "data" / "exemplos" / "exemplo_sintetico.tif"


def ensure_dir(path: PathLike) -> Path:
    """Create directory ``path`` (and parents) if missing; return as Path."""
    p = Path(path)
    p.mkdir(parents=True, exist_ok=True)
    return p


def read_raster(
    path: PathLike,
) -> Tuple[np.ndarray, Optional[tuple], Optional[str]]:
    """Read a GeoTIFF (or similar) into a NumPy array.

    Returns
    -------
    array : ndarray
        Shape ``(bands, rows, cols)`` if multi-band, else ``(rows, cols)``.
    transform : tuple or None
        Affine geotransform when available (GDAL/rasterio); else None.
    projection : str or None
        WKT / CRS string when available; else None.

    Backend order: rasterio → GDAL (osgeo) → tifffile (pixels only).
    """
    path = Path(path)
    if not path.is_file():
        raise FileNotFoundError(f"Raster not found: {path}")

    # 1) rasterio (preferred)
    try:
        import rasterio

        with rasterio.open(path) as ds:
            data = ds.read()  # (bands, rows, cols)
            transform = tuple(ds.transform)[:6] if ds.transform else None
            projection = ds.crs.to_wkt() if ds.crs else None
        if data.shape[0] == 1:
            data = data[0]
        return data, transform, projection
    except ImportError:
        pass

    # 2) GDAL
    try:
        from osgeo import gdal
        from osgeo.gdalconst import GA_ReadOnly

        gdal.UseExceptions()
        ds = gdal.Open(str(path), GA_ReadOnly)
        if ds is None:
            raise RuntimeError(f"GDAL failed to open: {path}")
        bands = ds.RasterCount
        rows, cols = ds.RasterYSize, ds.RasterXSize
        if bands == 1:
            data = ds.GetRasterBand(1).ReadAsArray().astype(np.float64)
        else:
            data = np.zeros((bands, rows, cols), dtype=np.float64)
            for b in range(bands):
                data[b] = ds.GetRasterBand(b + 1).ReadAsArray()
        transform = ds.GetGeoTransform()
        projection = ds.GetProjection() or None
        ds = None
        return data, transform, projection
    except ImportError:
        pass

    # 3) tifffile (no geo metadata)
    try:
        import tifffile

        data = tifffile.imread(str(path))
        # tifffile often returns (rows, cols, bands) or (rows, cols)
        if data.ndim == 3 and data.shape[-1] <= 20:
            # assume channels-last → band-first
            data = np.moveaxis(data, -1, 0)
        return np.asarray(data), None, None
    except ImportError as exc:
        raise ImportError(
            "Need rasterio, GDAL (osgeo), or tifffile to read rasters. "
            "Install via conda (environment.yml) or pip (requirements.txt)."
        ) from exc
