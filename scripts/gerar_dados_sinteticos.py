#!/usr/bin/env python3
"""Gera nove bandas artificiais, sem localização ou significado radiométrico."""
from pathlib import Path

import numpy as np
import rasterio
from rasterio.transform import from_origin

OUTPUT = Path(__file__).resolve().parents[1] / 'data/exemplos/exemplo_sintetico.tif'


def generate():
    rng = np.random.default_rng(20261115)
    y, x = np.mgrid[:96, :96] / 95
    patterns = np.stack([
        x, y, np.sin(4 * np.pi * x) * np.cos(3 * np.pi * y),
        ((x - .5)**2 + (y - .5)**2 < .08).astype(float),
    ])
    weights = rng.uniform(-.3, .7, (9, 4))
    bands = 500 + 300 * np.einsum('bc,cyx->byx', weights, patterns)
    bands += rng.normal(0, 12, bands.shape)
    return bands.astype('float32')


def main():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    with rasterio.open(
        OUTPUT, 'w', driver='GTiff', height=96, width=96, count=9,
        dtype='float32', transform=from_origin(0, 96, 1, 1),
        compress='deflate',
    ) as dataset:
        dataset.write(generate())
        dataset.update_tags(
            SOURCE='Synthetic data generated by scripts/gerar_dados_sinteticos.py',
            LICENSE='CC-BY-4.0', SEED='20261115',
            UNITS='arbitrary; not reflectance or temperature',
            COORDINATES='arbitrary grid; not a geographic location',
        )
        for band in range(1, 10):
            dataset.set_band_description(band, f'Canal artificial {band}')
    print(OUTPUT)


if __name__ == '__main__':
    main()
